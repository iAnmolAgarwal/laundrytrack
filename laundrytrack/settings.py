# Email (Django 6.1 MAILERS). Three transports, picked from .env:
#   1. HTTPS relay (Google Apps Script web app) - works on networks that block SMTP ports
#   2. Gmail SMTP with an app password
#   3. no credentials: emails are written to ./sent_emails/ so the app still works
SMTP_USER = os.environ.get("EMAIL_HOST_USER", "").strip()
SMTP_PASSWORD = os.environ.get("EMAIL_HOST_PASSWORD", "").replace(" ", "")
MAIL_WEBHOOK_URL = os.environ.get("MAIL_WEBHOOK_URL", "").strip()
MAIL_WEBHOOK_TOKEN = os.environ.get("MAIL_WEBHOOK_TOKEN", "").strip()
EMAIL_IS_LIVE = bool(MAIL_WEBHOOK_URL or (SMTP_USER and SMTP_PASSWORD))
DEFAULT_FROM_EMAIL = f"LaundryTrack <{SMTP_USER}>" if SMTP_USER else "LaundryTrack <laundrytrack@localhost>"
if MAIL_WEBHOOK_URL:
    MAILERS = {
        "default": {
            "BACKEND": "laundry.services.relay_backend.AppsScriptEmailBackend",
            "OPTIONS": {"url": MAIL_WEBHOOK_URL, "token": MAIL_WEBHOOK_TOKEN, "timeout": 30},
        },
    }
elif SMTP_USER and SMTP_PASSWORD:
    MAILERS = {
        "default": {
            "BACKEND": "django.core.mail.backends.smtp.EmailBackend",
            "OPTIONS": {
                "host": "smtp.gmail.com",
                "port": 587,
                "username": SMTP_USER,
                "password": SMTP_PASSWORD,
                "use_tls": True,
                "timeout": 12,
            },
        },
    }
else:
    MAILERS = {
        "default": {
            "BACKEND": "django.core.mail.backends.filebased.EmailBackend",
            "OPTIONS": {"file_path": str(BASE_DIR / "sent_emails")},
        },
    }
